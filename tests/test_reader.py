from __future__ import annotations

import json

from codeappendix.config import Config, apply
from codeappendix.reader import (
    decode,
    load_all,
    looks_generated,
    looks_minified,
    looks_vendored,
)
from codeappendix.scanner import R_BINARY, R_EMPTY, R_GENERATED, R_MINIFIED, R_VENDORED, scan


def load(root, cfg=None):
    cfg = cfg or Config()
    result = scan(root, cfg)
    files = load_all(result, cfg)
    return {f.rel: f for f in files}, dict(result.skipped)


def test_decode_variants():
    assert decode("xin chào".encode("utf-8")) == ("xin chào", "utf-8")
    assert decode(b"\xef\xbb\xbfabc") == ("abc", "utf-8-sig")
    assert decode("héllo".encode("utf-16")) == ("héllo", "utf-16")
    # cp1258 spells "Việt" as "ê" + combining dot below; the result is NFC.
    text, enc = decode(b"Vi\xea\xf2t")
    assert enc == "cp1258" and text == "Việt"


def test_newlines_tabs_and_control_characters(make_project):
    root = make_project({"a.c": b"int main() {\r\n\treturn 0;\x0c\r\n}\r\n\r\n\r\n"})
    files, _ = load(root)
    assert files["a.c"].lines == ["int main() {", "    return 0;", "}"]


def test_tab_size(make_project):
    root = make_project({"a.go": "func a() {\n\tx := 1\n}\n"})
    files, _ = load(root, apply(Config(), {"tab_size": 8}))
    assert files["a.go"].lines[1] == "        x := 1"


def test_leading_blank_lines_kept_for_numbering(make_project):
    root = make_project({"a.py": "\n\nx = 1\n"})
    files, _ = load(root)
    assert files["a.py"].lines == ["", "", "x = 1"]
    files, _ = load(root, apply(Config(), {"line_numbers": False}))
    assert files["a.py"].lines == ["x = 1"]


def test_binary_empty_generated_minified_vendored(make_project):
    root = make_project({
        "bin.py": b"abc\x00def",
        "empty.py": "\n\n",
        "migrations/0001_initial.py": "# Generated by Django 4.2 on 2024-01-01\nfrom django.db import migrations\n",
        "bundle.js": "var a=1;" * 400 + "\n",
        "vendor.css": "/*!\n * Bootstrap  v5.3.8 (https://getbootstrap.com/)\n */\n:root{}\n",
        "ok.sql": "CREATE TABLE t (id INT GENERATED BY DEFAULT AS IDENTITY);\n",
    })
    files, skipped = load(root)
    assert list(files) == ["ok.sql"]
    assert skipped["bin.py"] == R_BINARY
    assert skipped["empty.py"] == R_EMPTY
    assert skipped["migrations/0001_initial.py"] == R_GENERATED
    assert skipped["bundle.js"] == R_MINIFIED
    assert skipped["vendor.css"] == R_VENDORED


def test_explicit_include_keeps_generated(make_project):
    root = make_project({"api.py": "# Code generated by tool. DO NOT EDIT.\nx = 1\n"})
    files, _ = load(root, apply(Config(), {"include": ["api.py"]}))
    assert "api.py" in files


def test_heuristics():
    assert looks_generated(["// Code generated by protoc-gen-go. DO NOT EDIT."])
    assert not looks_generated(["x = 1  # generated by hand"])
    assert looks_minified(["a" * 5000])
    assert not looks_minified(["a" * 5000] + ["b"] * 100)
    assert looks_vendored(["/*! jQuery v3.7.1 | (c) OpenJS Foundation | jquery.org/license */"])
    assert not looks_vendored(["/*! my notes */", "body {}"])


def test_notebook_code_cells(make_project):
    nb = {
        "cells": [
            {"cell_type": "markdown", "source": ["# Title"]},
            {"cell_type": "code", "source": ["import numpy as np\n", "x = np.zeros(3)"], "outputs": []},
            {"cell_type": "code", "source": "", "outputs": []},
            {"cell_type": "code", "source": "print(x)", "outputs": []},
        ],
        "metadata": {"kernelspec": {"language": "python"}},
    }
    root = make_project({"analysis.ipynb": json.dumps(nb)})
    files, _ = load(root)
    src = files["analysis.ipynb"]
    assert src.lines == ["# [1]", "import numpy as np", "x = np.zeros(3)", "", "# [2]", "print(x)"]
    assert src.language == "Jupyter Notebook (Python)"


def test_max_lines_keeps_head_and_tail(make_project):
    root = make_project({"a.py": "\n".join(f"x{i} = {i}" for i in range(1, 101)) + "\n"})
    files, _ = load(root, apply(Config(), {"max_lines": 10}))
    src = files["a.py"]
    assert src.total_lines == 100
    assert src.omitted == (6, 90)
    assert src.lines[:5] == [f"x{i} = {i}" for i in range(1, 6)]
    assert src.lines[5:] == [f"x{i} = {i}" for i in range(96, 101)]


def test_ambiguous_extension_is_resolved_from_content(make_project):
    root = make_project({
        "AppDelegate.m": '#import "AppDelegate.h"\n@implementation AppDelegate\n@end\n',
        "solve.m": "function x = solve(A, b)\n  x = A \\ b;\nend\n",
    })
    files, _ = load(root)
    assert files["AppDelegate.m"].language == "Objective-C"
    assert files["solve.m"].language == "Matlab"
    assert files["solve.m"].lexer
